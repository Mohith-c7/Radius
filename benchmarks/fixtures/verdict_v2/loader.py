"""Loader for the Verdict v2 Stage-A/Stage-B input bundles (VS-01).

``benchmarks/fixtures/verdict_v2/<fixture>/inputs.json`` is generated by
``scripts/verdict_v2_make_fixtures.py`` and conforms to the frozen input contracts
``radius_evidence.domain.inputs``. This module turns it into those dataclasses::

    from loader import load_bundle, stage_a, stage_b
    sa = stage_a("08_multi_criterion_partial_evidence", mode="gold")
    sb = stage_b("08_multi_criterion_partial_evidence", mode="gold", scenario="head")

Modes: ``gold`` (links from expected.json, normative) and ``auto`` (real LK-02/LK-03 links).
Scenarios: ``base``, ``head`` (the CI result of the PR head), ``head_with_probes``.
Needs ``packages/evidence/src`` on ``sys.path`` (it is added here when missing).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
_EVIDENCE_SRC = HERE.parents[2] / "packages" / "evidence" / "src"
if str(_EVIDENCE_SRC) not in sys.path:
    sys.path.append(str(_EVIDENCE_SRC))

from radius_evidence.domain.inputs import (  # noqa: E402
    CaseOutcomeInput,
    StageAInput,
    StageBInput,
)

MODES = ("gold", "auto")
SCENARIOS = ("base", "head", "head_with_probes")


def fixture_names() -> list[str]:
    return sorted(p.parent.name for p in HERE.glob("*/inputs.json"))


def load_bundle(fixture: str) -> dict[str, Any]:
    return json.loads((HERE / fixture / "inputs.json").read_text(encoding="utf-8"))


def stage_a(fixture: str, mode: str = "gold") -> StageAInput:
    return StageAInput.from_dict(load_bundle(fixture)["modes"][mode]["stage_a"])


def stage_b(fixture: str, mode: str = "gold", scenario: str = "head") -> StageBInput:
    bundle = load_bundle(fixture)
    block = bundle["stage_b"][scenario]
    return StageBInput(
        stage_a=StageAInput.from_dict(bundle["modes"][mode]["stage_a"]),
        cases=tuple(CaseOutcomeInput.from_dict(c) for c in block["cases"]),
        uploads=int(block["uploads"]),
        flaky_test_ids=frozenset(block["flaky_test_ids"]),
        flaky_scores=dict(block["flaky_scores"]),
        results_received=bool(block["results_received"]),
        ci_failed_cases=int(block["ci_failed_cases"]),
    )
