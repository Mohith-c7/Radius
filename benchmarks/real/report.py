"""Regenerate docs/benchmarks/REAL_REPO_BENCHMARK.md (and corpus.json `observed`) from raw results.

    python benchmarks/real/report.py

Every number in the generated report is computed here from benchmarks/real/results/*.jsonl.
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
from metrics import aggregate, classify_miss, wilson  # noqa: E402

METHODS = (("full", "Full suite"), ("convention", "Filename convention"), ("radius", "Radius (graph + verdict)"))
OUT = REPO / "docs" / "benchmarks" / "REAL_REPO_BENCHMARK.md"


def load() -> tuple[list[dict], list[dict]]:
    metas, rows = [], []
    for path in sorted((HERE / "results").glob("*.jsonl")):
        for line in path.read_text().splitlines():
            rec = json.loads(line)
            (metas.append(rec["meta"]) if "meta" in rec else rows.append(rec))
    return metas, rows


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def ci(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {pct(k / n if n else None)} [{pct(lo)}, {pct(hi)}]"


def table(header: list[str], body: list[list[object]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(lines)


def method_table(rows: list[dict]) -> str:
    body = []
    for key, name in METHODS:
        a = aggregate(rows, key)
        body.append([name, ci(a["caught"], a["detected"]), ci(a["missed"], a["detected"]),
                     pct(a["recall"]), pct(a["precision"]), pct(a["fraction"]),
                     "n/a" if a["seconds"] is None else f"{a['seconds']:.2f}"])
    return table(["Method", "Regression detection [95% CI]", "Missed regression [95% CI]",
                  "Mean file recall", "Mean file precision", "Test files selected (mean)",
                  "Mean wall-clock s / scenario"], body)


def verdict_table(rows: list[dict]) -> str:
    groups = (("detected (full suite fails)", [r for r in rows if r["truth_failing"]]),
              ("undetected (full suite passes)", [r for r in rows if not r["truth_failing"]]))
    verdicts = ("failed", "insufficient_evidence", "verified", "crashed")
    body = []
    for label, grp in groups:
        c = Counter(r["radius"]["verdict"] for r in grp)
        body.append([label, len(grp), *(c.get(v, 0) for v in verdicts)])
    return table(["Ground truth", "n", *verdicts], body)


def main() -> int:
    metas, rows = load()
    if not rows:
        print("no results in benchmarks/real/results", file=sys.stderr)
        return 1
    mutants = [r for r in rows if not r["kind"].startswith("structural:")]
    structural = [r for r in rows if r["kind"].startswith("structural:")]
    det = [r for r in mutants if r["truth_failing"]]
    und = [r for r in mutants if not r["truth_failing"]]
    flaky = [r for r in rows if r["flaky"]]
    rad = aggregate(mutants, "radius")
    sha = sorted({m["source_sha"] for m in metas})
    md: list[str] = []
    w = md.append
    w("# Real-code mutation benchmark (self-evaluation corpus)\n")
    w("> Generated by `python benchmarks/real/report.py` from `benchmarks/real/results/*.jsonl`. "
      "Do not edit by hand; every number below is computed from the raw per-scenario records.\n")
    w("**Scope warning.** The corpus is Radius's *own* Python packages. This is a self-evaluation on a "
      f"small sample ({len(mutants)} mutants, {len(structural)} structural scenarios, {len(metas)} subjects, "
      "one language). No external open-source repository was executed in this session. The numbers "
      "below must not be generalised to other codebases.\n")

    w("## 1. Research questions and hypotheses (protocol fixed before the reported run)\n")
    w("The methods, metrics and classification rules below were implemented in `run.py`/`metrics.py` "
      "before the reported run (an 8-mutant pilot on two subjects was used only to debug the harness and "
      "is not included).\n")
    w("- **RQ1 (safety).** Does Radius ever return `verified` for a change that the full suite detects? "
      "*H1: false-safe rate = 0.* Any non-zero value is a defect.")
    w("- **RQ2 (detection).** What fraction of full-suite-detected regressions does each method's selected "
      "test set detect? *H2: Radius > filename convention; full suite = 100% by construction.*")
    w("- **RQ3 (cost).** What fraction of test files does each method run, and at what wall-clock? "
      "*H3: Radius runs fewer test files than the full suite, more than the convention baseline.*")
    w("- **RQ4 (abstention).** How often does Radius abstain (`insufficient_evidence`)? No target; reported.")
    w("- **RQ5 (calibration).** Does the heuristic score separate detected from undetected changes? "
      "*H5: too little data to calibrate; the score stays a heuristic, not a probability.*\n")

    w("## 2. Corpus\n")
    w(f"Source repository commit: `{', '.join(sha)}`. Subjects are exported with `git archive <sha> packages` "
      "(so concurrent working-tree edits do not leak in), copied into a fresh scratch git repo, and their "
      "sibling `radius_*` imports are satisfied read-only from the same archive via `PYTHONPATH`. "
      "Radius itself (the tool under test) ran from the working tree; `tool_working_tree_dirty` records "
      "whether that tree differed from the commit.\n")
    w(table(["Subject", "Package", "Read-only deps", "Source files", "Test files", "Baseline full suite",
             "Baseline s", "Seed", "Mutants", "Tool tree dirty"],
            [[m["subject"], f"`{m['package']}`", ", ".join(f"`{d}`" for d in m["deps_readonly"]),
              m["source_files"], m["test_files"],
              "pass" if not m["baseline_failing"] and m["baseline_rc"] == 0 else f"FAIL {m['baseline_failing']}",
              m["baseline_seconds"], m["seed"],
              sum(1 for r in mutants if r["subject"] == m["subject"]), m.get("tool_working_tree_dirty")]
             for m in metas]))
    w("\nInclusion/exclusion criteria and the (unexecuted) external-OSS schema are in "
      "`benchmarks/real/corpus.json`. External candidates are marked `\"executed\": false`; no numbers exist for them.\n")

    w("## 3. Methodology\n")
    w("- **Scenarios.** Per subject, `--mutants N` (file, site) pairs are sampled with `random.Random(seed)` "
      "from all mutation sites in non-test `src/**/*.py`. Operators: `flip_comparison` (e.g. `<`→`>=`, "
      "`==`→`!=`, `is`→`is not`, `in`→`not in`), `negate_condition` (`if/while c`→`not (c)`), "
      "`off_by_one` (int literal +1), `return_none` (`return e`→`return None`), `swap_add_sub` (`+`↔`-`). "
      "Each mutation is a minimal textual splice of the AST node's span; the rest of the file is byte-identical. "
      "Each scenario is one commit on its own branch; Radius gets `git diff main...HEAD`.")
    w("- **Structural scenarios** (one each per subject, targeting the source module imported by the most "
      "other modules): mutate that shared helper; delete it; rename it without updating imports; "
      "change the `package.json` manifest (benign).")
    w("- **Ground truth** (independent of Radius): full pytest suite on the scenario commit; the set of test "
      "files with a FAILED/ERROR item. Suites that fail are re-run once; a differing failing set flags the "
      "scenario as flaky. *Detected* = ≥1 failing test file. *Undetected* mutants (full suite passes) may be "
      "equivalent mutants or test-suite gaps; a `verified` verdict on them is not provably wrong and they are "
      "reported separately.")
    w("- **Radius** runs through `create_local_orchestrator()` exactly as `benchmarks/scenarios/harness.py` "
      "does: real parser + import graph, graph/convention/full-suite-fallback selection, the real "
      "`SubprocessTestRunner` executing the selected tests, and the real scorer/verdict on that outcome. "
      "Radius's run result is aggregate, so its failing *files* are attributed by re-running only the "
      "selected files (excluded from Radius wall-clock).\n")

    w("## 4. Baselines\n")
    w("- **Full suite:** all `tests/**/test_*.py`. Detects 100% of detected mutants by definition; its "
      "value is the cost reference.")
    w("- **Filename convention:** test files whose stem (minus `test_`) contains the changed module's stem "
      "(e.g. `module_resolver.py` → `test_module_resolver.py`). Selected files are executed for real. "
      "No selection ⇒ nothing runs ⇒ counts as a miss on a detected mutant.")
    w("- **Radius:** as above. Pants/Bazel-style baselines were not run (not installed; no external code allowed).\n")

    w("## 5. Metric definitions\n")
    w("Over *detected* mutants (full suite has ≥1 failing test file), per method:\n")
    w("- **Regression detection rate** = scenarios where ≥1 of the method's selected test files fails ÷ detected.")
    w("- **Missed-regression rate** = 1 − detection rate (selected tests all pass, error-free, or none selected).")
    w("- **False-safe verdict rate** (Radius only) = Radius verdict `verified` ÷ detected.")
    w("- **Abstention rate** (Radius only) = `insufficient_evidence` ÷ all mutants.")
    w("- **File recall** = |selected ∩ failing| ÷ |failing| (mean over detected mutants). "
      "**File precision** = |selected ∩ failing| ÷ |selected| (mean over detected mutants with ≥1 selected file).")
    w("- **Test files selected** = |selected| ÷ |all test files|, mean over all mutants (selected = executed).")
    w("- **Wall-clock** = mean seconds per scenario: full = one full pytest run; convention = pytest on its "
      "selection; Radius = whole pipeline (parse, graph, select, run, score). Subjects ran as 4 parallel "
      "processes on one machine, so absolute times include contention.")
    w("- **95% CI**: Wilson score interval.\n")

    w("## 6. Results\n")
    w("### 6.1 Mutant population\n")
    w(table(["Subject", "Mutants", "Detected by full suite", "Undetected", "Flaky (rerun differed)"],
            [[m["subject"], *(lambda s: [len(s), sum(1 for r in s if r["truth_failing"]),
                                         sum(1 for r in s if not r["truth_failing"]),
                                         sum(1 for r in s if r["flaky"])])(
                [r for r in mutants if r["subject"] == m["subject"]])] for m in metas]
            + [["**all**", len(mutants), len(det), len(und), sum(1 for r in mutants if r["flaky"])]]))
    ops = Counter(r["kind"] for r in mutants)
    opd = Counter(r["kind"] for r in det)
    w("\nBy operator (detected / sampled): " + ", ".join(f"`{k}` {opd[k]}/{v}" for k, v in sorted(ops.items())) + ".\n")

    w("### 6.2 Methods on detected mutants (all subjects pooled)\n")
    w(method_table(mutants) + "\n")
    w(f"- **False-safe verdict rate (Radius `verified` on a detected mutant): {ci(rad['false_safe'], rad['detected'])}.**")
    w(f"- Radius abstention (`insufficient_evidence`) over all mutants: {ci(rad['abstain'], rad['n'])}.")
    fails_as_failed = sum(r["radius"]["verdict"] == "failed" for r in det)
    w(f"- Radius verdict `failed` on detected mutants: {ci(fails_as_failed, len(det))}.\n")
    conv = aggregate(mutants, "convention")
    full = aggregate(mutants, "full")
    w("**Against the hypotheses** (mechanical comparison of the numbers above, no significance test):\n")
    w(f"- H1 (false-safe = 0): {'held' if rad['false_safe'] == 0 else 'REJECTED'} "
      f"({rad['false_safe']} false-safe of {rad['detected']}; this sample cannot rule out a true rate up to "
      f"{pct(rad['false_safe_ci'][1])}, the Wilson upper bound).")
    w(f"- H2 (Radius detects more than convention): Radius {rad['caught']}/{rad['detected']} vs convention "
      f"{conv['caught']}/{conv['detected']} → {'held' if rad['caught'] > conv['caught'] else 'not supported'}.")
    w(f"- H3 (Radius runs fewer files than full, more than convention): Radius {pct(rad['fraction'])} vs full "
      f"{pct(full['fraction'])} vs convention {pct(conv['fraction'])} → "
      f"{'held' if conv['fraction'] < rad['fraction'] < full['fraction'] else 'not supported'}. "
      f"Mean wall-clock per scenario: Radius {rad['seconds']:.2f}s (includes analysis) vs full suite "
      f"{full['seconds']:.2f}s.\n")
    w("### 6.3 Per subject\n")
    for m in metas:
        sub = [r for r in mutants if r["subject"] == m["subject"]]
        w(f"**{m['subject']}**\n")
        w(method_table(sub) + "\n")
    w("### 6.4 Radius verdicts vs ground truth (mutants)\n")
    w(verdict_table(mutants) + "\n")
    w("A `verified` in the *undetected* row is not provably wrong: no test in the full suite detects that mutant either.\n")

    w("### 6.5 Structural scenarios\n")
    w(table(["Subject", "Scenario", "Full suite failing files", "Convention sel/fail", "Radius sel", "Radius run",
             "Verdict", "Score", "False safe"],
            [[r["subject"], r["kind"].removeprefix("structural:"), len(r["truth_failing"]),
              f"{len(r['convention']['selected'])}/{len(r['convention']['failing'])}",
              f"{len(r['radius']['selected'])}/{r['total_test_files']}", r["radius"]["run"],
              r["radius"]["verdict"], r["radius"]["score"],
              "YES" if r["truth_failing"] and r["radius"]["verdict"] == "verified" else "no"]
             for r in structural]) + "\n")

    w("### 6.6 Score calibration (heuristic score vs outcome, all mutants)\n")
    buckets = [(0, 40), (40, 60), (60, 80), (80, 101)]
    body = []
    for lo, hi in buckets:
        b = [r for r in mutants if r["radius"]["score"] is not None and lo <= r["radius"]["score"] < hi]
        k = sum(1 for r in b if r["truth_failing"])
        body.append([f"[{lo}, {min(hi, 100)}{']' if hi > 100 else ')'}", len(b), k,
                     ci(k, len(b)) if b else "n/a"])
    w(table(["Score bucket", "n", "Detected by full suite", "Share detected [95% CI]"], body) + "\n")
    w("The score is computed *after* Radius has run the selected tests, so low scores largely reflect "
      "observed failures rather than a prediction. With these sample sizes the CIs are wide; the score "
      "remains a **heuristic, not a probability**, and no calibration claim is made.\n")

    w("## 7. Failure analysis\n")
    w("Every detected mutant a selection method missed, classified by `metrics.classify_miss`:\n")
    w("- *selection error*: no failing test file was selected;")
    w("- *isolation/environment*: a failing file was selected but did not fail when run as part of the "
      "method's selection (order/isolation dependence or environment);")
    w("- *abstained*: Radius returned `insufficient_evidence` (missed by selection, but not a false-safe verdict).")
    w("Test-quality gaps appear as *undetected* mutants (§6.1), since a detected mutant by definition has a test that catches it.\n")
    miss_rows = []
    for r in det:
        for key, name in METHODS[1:]:
            cls = classify_miss(r, key)
            if cls:
                miss_rows.append([r["subject"], f"`{r['file'].removeprefix('src/')}`:{r['line']}", r["kind"], name,
                                  ", ".join(Path(t).name for t in r["truth_failing"]),
                                  len(r[key]["selected"]),
                                  r["radius"]["verdict"] if key == "radius" else "-", cls])
    if miss_rows:
        w(table(["Subject", "Site", "Operator", "Method", "Failing test files (truth)", "Selected",
                 "Radius verdict", "Classification"], miss_rows) + "\n")
        cc = Counter((row[3], row[7]) for row in miss_rows)
        w("Totals: " + "; ".join(f"{m} – {c}: {n}" for (m, c), n in sorted(cc.items())) + ".\n")
    else:
        w("No misses.\n")
    for _, name in METHODS[1:]:
        n = sum(1 for row in miss_rows if row[3] == name)
        w(f"- {name}: {n} missed detected mutant(s).")
    w("")
    if flaky:
        w(f"Flaky scenarios (full-suite rerun differed): {', '.join(r['subject'] + '#' + str(r['id']) for r in flaky)}.\n")
    else:
        w("No scenario's failing set changed on rerun (0 flaky).\n")

    w("## 8. Limitations\n")
    w("- **Self-evaluation bias:** the corpus is Radius's own code; its import style matches what Radius's "
      "resolver was built and tested against. Results are likely optimistic for other codebases.")
    w("- **Python only, pytest only, small N** (see §6.1 for counts; CIs are wide).")
    w("- **No external OSS executed:** cloning/executing external code was not permitted in this session; "
      "`corpus.json` lists candidates with `\"executed\": false` and no numbers.")
    w("- **Mutants are synthetic** (5 simple operators); real regressions can be semantic/multi-file. "
      "Undetected mutants are not split into equivalent vs test-gap (not analysed manually).")
    w("- **Packages, not whole repos:** subjects are single packages with sibling deps on PYTHONPATH; "
      "changes to those deps are not scenarios.")
    w("- **Wall-clock** measured with 4 subjects in parallel on one machine; the suites are seconds-long, so "
      "Radius's fixed analysis overhead dominates and time savings here say nothing about large suites.")
    w("- **Broad selection makes detection cheap here:** Radius selected about half of each small suite on average "
      "(§6.2), so 100% detection does not show that the graph is precise; detection on larger suites with "
      "deeper import fan-out is untested. Undetected mutants (§6.4) show the opposite risk: Radius can return "
      "`verified` where the existing tests are simply too weak, which no selection method can fix.")
    w("- **File-level ground truth:** failing *test files*, not test cases.")
    w("- Radius ran from a working tree that other agents were editing concurrently (see `Tool tree dirty`).\n")

    w("## 9. Reproduction\n")
    w("```bash\n. .venv/bin/activate\n"
      f"python benchmarks/real/run.py --subjects {' '.join(m['subject'] for m in metas)} "
      f"--mutants {max(m['mutants_requested'] for m in metas)} --seed {metas[0]['seed']}\n"
      "python benchmarks/real/report.py\n"
      "python -m pytest benchmarks/real/tests -q -o addopts=--import-mode=importlib\n```\n")
    w("No third-party dependencies beyond the repository's own dev environment (pytest). "
      f"Python {metas[0].get('python', '?')}.\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(md))

    corpus_path = HERE / "corpus.json"
    corpus = json.loads(corpus_path.read_text())
    by = {m["subject"]: m for m in metas}
    for s in corpus["subjects"]:
        m = by.get(s["subject"])
        if m:
            s["source_sha"] = m["source_sha"]
            s["observed"] = {k: m[k] for k in ("baseline_failing", "baseline_rc", "baseline_seconds",
                                               "test_files", "source_files", "seed", "mutants_requested")}
    corpus_path.write_text(json.dumps(corpus, indent=2) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
