"""Collapsible "AI review (advisory)" section for the Radius PR comment (DEC-042).

Input is the stored, already validated review payload
(``radius_shared.ai_review.StoredAiReview.to_payload``). It is still treated as untrusted:
text is Markdown-escaped, paths are shown as code spans, and the section is capped. It is
appended to the PR comment only, never to the Check Run, and it never changes the verdict,
the score or the check conclusion.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from typing import Any

MAX_SECTION_CHARS = 6_000
#: GitHub rejects issue comments above 65,536 characters.
COMMENT_CHAR_LIMIT = 65_000

_HEADINGS = (
    ("risks", "Main risks"),
    ("tests", "Tests that matter"),
    ("missing_evidence", "Missing evidence"),
    ("next_steps", "Next steps"),
)
#: Markdown emphasis, code, links and tables. ``#`` is left alone: text never starts a
#: line here (so it cannot become a heading) and the ``&#64;`` entity needs it.
_ESCAPE = re.compile(r"([\\`*_{}\[\]()+!|~])")


def _text(value: Any) -> str:
    text = " ".join(str(value or "").split())
    # HTML entities for &, <, > and @: no tags and no @mention notifications.
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("@", "&#64;")
    return _ESCAPE.sub(r"\\\1", text)


def _code(path: Any) -> str:
    clean = " ".join(str(path or "").split()).replace("`", "'")[:200]
    return f"`{clean}`"


def render_ai_review_section(payload: Mapping[str, Any] | None) -> str:
    """The Markdown section, or ``""`` when there is no usable review."""

    if not payload or payload.get("status") != "ok" or not payload.get("summary"):
        return ""
    model = _code(payload.get("model") or "unknown model")
    lines = [
        "<details>",
        "<summary><strong>AI review (advisory)</strong></summary>",
        "",
        f"_AI-generated by {model} from Radius evidence and diff excerpts. Advisory only: it "
        "does not change the Radius verdict, score or check result. Verify every point._",
        "",
        f"**What changes:** {_text(payload.get('summary'))}",
    ]
    for key, heading in _HEADINGS:
        items = payload.get(key) or []
        if not isinstance(items, list) or not items:
            continue
        lines += ["", f"**{heading}**", ""]
        for item in items[:5]:
            if not isinstance(item, Mapping):
                continue
            files = [f for f in (item.get("files") or []) if isinstance(f, str)][:5]
            cited = f" ({', '.join(_code(f) for f in files)})" if files else ""
            lines.append(f"- {_text(item.get('text'))}{cited}")
    notes = payload.get("notes") or {}
    if isinstance(notes, Mapping) and notes.get("injection_flags"):
        lines += [
            "",
            "_Radius flagged text in this PR that looks like instructions to an AI; it was "
            "treated as data._",
        ]
    lines += ["", "</details>"]
    section = "\n".join(lines)
    if len(section) > MAX_SECTION_CHARS:
        section = section[: MAX_SECTION_CHARS - 40].rsplit("\n", 1)[0] + "\n- ...\n\n</details>"
    return section


def append_section(body: str, section: str) -> str:
    """``body`` plus ``section`` when it fits GitHub's comment limit, else ``body``."""

    if not section:
        return body
    combined = f"{body}\n\n{section}"
    return combined if len(combined) <= COMMENT_CHAR_LIMIT else body


__all__ = ["COMMENT_CHAR_LIMIT", "append_section", "render_ai_review_section"]
