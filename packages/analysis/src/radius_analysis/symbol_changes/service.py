def _file_change(
    fd: FileDiff, language: str, level: FileLevel, notes: list[str], extra: list[str]
) -> FileChange:
    return FileChange(
        path=fd.path,
        old_path=fd.old_path if fd.old_path != fd.path else None,
        status=fd.status,
        language=language,
        level=level,
        notes=tuple(dict.fromkeys([*notes, *extra])),
    )


def _generated_header(data: bytes) -> bool:
    head = data[:2048].decode("utf-8", errors="ignore").lower()
    first_lines = "\n".join(head.split("\n")[:5])
    return any(marker in first_lines for marker in _GENERATED_MARKERS)


def extract_symbol_changes(
    repo_base: SnapshotReader | None,
    repo_head: SnapshotReader,
    diff_or_refs: str | RefRange,
    options: ExtractionOptions | None = None,
    *,
    diff_provider: GitDiffProvider | None = None,
    clock: Callable[[], float] = time.monotonic,
) -> SymbolChangeSet:
    """Extract the changed symbols between two snapshots.

    ``repo_base`` may be ``None``: the base is then rebuilt from the head
    snapshot and the diff (see :class:`DiffReversedSnapshot`). When
    ``diff_or_refs`` is a :class:`RefRange` the diff comes from
    ``diff_provider`` (default: local ``git diff``) and a missing base reader is
    created from git.
    """

    opts = options or ExtractionOptions()
    started = clock()
    set_notes: set[str] = set()

    if isinstance(diff_or_refs, RefRange):
        provider = diff_provider
        if provider is None:
            from radius_analysis.infrastructure.git_diff_provider import (  # noqa: PLC0415
                SubprocessGitDiffProvider,
            )

            provider = SubprocessGitDiffProvider()
        diff_text = provider.get_diff(
            diff_or_refs.repository_path, diff_or_refs.base_ref, diff_or_refs.head_ref
        )
        if repo_base is None:
            repo_base = GitSnapshot(diff_or_refs.repository_path, diff_or_refs.base_ref)
    else:
        diff_text = diff_or_refs

    if len(diff_text.encode("utf-8", errors="ignore")) > opts.max_diff_bytes:
        return SymbolChangeSet(
            truncated=True, notes=("diff_too_large",), config=opts.to_config()
        )

    diffs = parse_unified_diff(diff_text)
    if repo_base is None:
        repo_base = DiffReversedSnapshot(repo_head, diffs)

    symbols: list[ChangedSymbol] = []
    unattributed: list[UnattributedHunk] = []
    file_changes: list[FileChange] = []
    units: list[_Unit] = []
    truncated = False

    ordered = sorted(diffs, key=lambda d: (d.path, d.old_path or ""))
    for position, fd in enumerate(ordered):
        path = fd.path
        language, suffix = detect_language(path)
        notes = list(fd.notes)

        glob = is_ignored(path, opts.ignore_globs) or (
            is_ignored(fd.old_path, opts.ignore_globs) if fd.old_path else None
        )
        if glob:
            file_changes.append(_file_change(fd, language, FileLevel.IGNORED, notes, [f"ignored:{glob}"]))
            continue
        if fd.mode_only:
            file_changes.append(_file_change(fd, language, FileLevel.NONE, notes, []))
            continue

        degrade: list[str] = []
        old_text = new_text = None
        if fd.binary:
            degrade.append("binary_file")
        elif position >= opts.max_files:
            degrade.append("max_files_exceeded")
            truncated = True
        elif clock() - started > opts.time_budget_seconds:
            degrade.append("timeout")
            truncated = True
        elif language == "unknown" or suffix is None:
            degrade.append("unsupported_language")
        else:
            old_text, new_text, degrade = _load_texts(fd, repo_base, repo_head, opts, notes)
            if "generated_header" in notes:
                notes.remove("generated_header")
                file_changes.append(_file_change(fd, language, FileLevel.IGNORED, notes, ["ignored:generated_header"]))
                continue

        unit = None
        if not degrade:
            try:
                unit = _build_unit(
                    len(units), fd, language, suffix, path, fd.old_path, old_text, new_text, degrade
                )
            except Exception as exc:  # never crash the pipeline on one file
                degrade.append(f"internal_error:{type(exc).__name__}")
                unit = None
        if unit is None:
            symbols.append(_file_level_symbol(fd, language, path, fd.old_path, [*notes, *degrade]))
            file_changes.append(_file_change(fd, language, FileLevel.FILE, notes, degrade))
            continue
        unit.notes.extend(notes)
        units.append(unit)
        file_changes.append(_file_change(fd, language, FileLevel.SYMBOL, notes, unit.notes))

    for unit in units:
        _match_in_file(unit, opts, set_notes)
        _attribute(unit, opts)

    # cross-file move detection among definitions that have no counterpart in-file
    pool_old = [(u, i) for u in units for i in u.unmatched_old]
    pool_new = [(u, i) for u in units for i in u.unmatched_new]
    cross = []
    if pool_old and pool_new:
        cross = _greedy_pairs(
            pool_old, pool_new, opts, [opts.max_similarity_pairs], set_notes, cross_file=True
        )
    cross_old = {(o[0].uid, o[1]) for o, _n, _s in cross}
    cross_new = {(n[0].uid, n[1]) for _o, n, _s in cross}

    for unit in units:
        for oi, ni, origin, score in unit.matched:
            sym = _emit_pair(unit, oi, unit, ni, origin, score)
            if sym is not None:
                symbols.append(sym)
        for oi in unit.unmatched_old:
            if (unit.uid, oi) not in cross_old:
                symbols.append(_emit_one_sided(unit, "old", oi))
        for ni in unit.unmatched_new:
            if (unit.uid, ni) not in cross_new:
                symbols.append(_emit_one_sided(unit, "new", ni))
        unattributed.extend(unit.unattributed)
    for (uo, oi), (un, ni), score in cross:
        sym = _emit_pair(uo, oi, un, ni, "cross", score)
        if sym is not None:
            symbols.append(sym)

    symbols.sort(key=ChangedSymbol.sort_key)
    unattributed.sort(key=UnattributedHunk.sort_key)
    file_changes.sort(key=lambda f: (f.path, f.old_path or ""))
    return SymbolChangeSet(
        symbols=tuple(symbols),
        unattributed_hunks=tuple(unattributed),
        files=tuple(file_changes),
        truncated=truncated,
        notes=tuple(sorted(set_notes)),
        config=opts.to_config(),
        algo_version=ALGO_VERSION,
    )


def _load_texts(
    fd: FileDiff,
    repo_base: SnapshotReader,
    repo_head: SnapshotReader,
    opts: ExtractionOptions,
    notes: list[str],
) -> tuple[str | None, str | None, list[str]]:
    degrade: list[str] = []
    old_text = new_text = None
    if fd.status is not FileStatus.ADDED and fd.status is not FileStatus.COPIED:
        data = repo_base.read(fd.old_path or fd.path)
        if data is None:
            degrade.append("snapshot_missing_base")
        elif len(data) > opts.max_file_bytes:
            degrade.append("file_too_large")
        elif b"\x00" in data[:8192]:
            degrade.append("binary_file")
        else:
            old_text, extra = _decode(data)
            notes.extend(f"base_{e}" for e in extra)
            if opts.detect_generated_headers and _generated_header(data):
                notes.append("generated_header")
    if fd.status is not FileStatus.DELETED:
        data = repo_head.read(fd.path)
        if data is None:
            degrade.append("snapshot_missing_head")
        elif len(data) > opts.max_file_bytes:
            degrade.append("file_too_large")
        elif b"\x00" in data[:8192]:
            degrade.append("binary_file")
        else:
            new_text, extra = _decode(data)
            notes.extend(f"head_{e}" for e in extra)
    return old_text, new_text, list(dict.fromkeys(degrade))


def _build_unit(
    uid: int,
    fd: FileDiff,
    language: str,
    suffix: str,
    path: str,
    old_path: str | None,
    old_text: str | None,
    new_text: str | None,
    degrade: list[str],
) -> _Unit | None:
    def index_of(text: str) -> FileIndex:
        if language == "python":
            return index_python(text)
        return index_ecmascript(text, suffix, language)

    old_side = new_side = None
    if old_text is not None:
        idx = index_of(old_text)
        if idx.parse_error:
            degrade.append(f"parse_error_base:{idx.parse_error}")
        else:
            old_side = _make_side(old_text, idx)
    if new_text is not None:
        idx = index_of(new_text)
        if idx.parse_error:
            degrade.append(f"parse_error_head:{idx.parse_error}")
        else:
            new_side = _make_side(new_text, idx)
    if degrade:
        return None
    return _Unit(
        uid=uid,
        fd=fd,
        language=language,
        path=path,
        old_path=old_path if old_path != path else None,
        old=old_side,
        new=new_side,
    )
