def detect_language(path: str) -> tuple[str, str | None]:
    """Return (language, grammar suffix); unknown suffixes give ``("unknown", None)``."""

    suffix = PurePosixPath(path).suffix.lower()
    found = _LANGUAGE_BY_SUFFIX.get(suffix)
    return found if found else ("unknown", None)


def is_ignored(path: str, globs: tuple[str, ...]) -> str | None:
    """Return the matching glob if ``path`` is configured away, else ``None``."""

    parts = path.split("/")
    for pattern in globs:
        if pattern.endswith("/"):
            if pattern[:-1] in parts[:-1]:
                return pattern
        elif "/" in pattern:
            if fnmatch.fnmatchcase(path, pattern):
                return pattern
        elif fnmatch.fnmatchcase(parts[-1], pattern):
            return pattern
    return None


def symbol_id(language: str, path: str, d: Defn) -> str:
    return f"{language}:{path}::{d.qualname}#{d.kind}@{d.signature_hash}"


def symbol_key(language: str, path: str, d: Defn) -> str:
    return f"{language}:{path}::{d.qualname}#{d.kind}"


def _decode(data: bytes) -> tuple[str, list[str]]:
    notes: list[str] = []
    if data.startswith(b"\xef\xbb\xbf"):
        data = data[3:]
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        text = data.decode("utf-8", errors="replace")
        notes.append("decode_errors")
    if "\r" in text:
        text = text.replace("\r\n", "\n")
        if "\r" in text:
            text = text.replace("\r", " ")  # keep git's line numbering
            notes.append("lone_cr_normalized")
    return text, notes


def _is_blank_or_comment(line: str, language: str) -> bool:
    stripped = line.strip()
    return not stripped or stripped.startswith(_COMMENT_PREFIXES.get(language, ("#",)))


