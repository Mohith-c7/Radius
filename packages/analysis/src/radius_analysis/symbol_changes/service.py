@dataclass(slots=True)
class _Side:
    index: FileIndex
    lines: list[str]
    owner: list[int]
    _comments: dict[int, list[str]] | None = None

    def comments_of(self, idx: int) -> list[str]:
        if self._comments is None:
            by_owner: dict[int, list[str]] = defaultdict(list)
            for start, _end, text in self.index.comments:
                own = self.owner[start] if 1 <= start < len(self.owner) else -1
                if own == -1 and self.index.module_index is not None:
                    own = self.index.module_index
                by_owner[own].append(" ".join(text.split()))
            self._comments = by_owner
        return self._comments.get(idx, [])


@dataclass(slots=True)
class _Unit:
    uid: int
    fd: FileDiff
    language: str
    path: str
    old_path: str | None
    old: _Side | None
    new: _Side | None
    notes: list[str] = field(default_factory=list)
    matched: list[tuple[int, int, str, float]] = field(default_factory=list)
    unmatched_old: list[int] = field(default_factory=list)
    unmatched_new: list[int] = field(default_factory=list)
    attr: dict[tuple[str, int], dict[int, list[set[int]]]] = field(default_factory=dict)
    changed_text: dict[tuple[str, int], list[str]] = field(default_factory=dict)
    unattributed: list[UnattributedHunk] = field(default_factory=list)

    @property
    def file_renamed(self) -> bool:
        return self.old_path is not None and self.old_path != self.path


def _make_side(text: str, index: FileIndex) -> _Side:
    lines = text.split("\n")
    return _Side(index=index, lines=lines, owner=paint_owners(index.defs, index.line_count))


# --------------------------------------------------------------------------- matching


def _ref_sort(unit: _Unit, d: Defn) -> tuple[Any, ...]:
    return (unit.path, d.qualname, d.kind, d.start)


def _greedy_pairs(
    olds: list[tuple[_Unit, int]],
    news: list[tuple[_Unit, int]],
    opts: ExtractionOptions,
    budget: list[int],
    notes: set[str],
    *,
    cross_file: bool = False,
) -> list[tuple[tuple[_Unit, int], tuple[_Unit, int], float]]:
    """Deterministic best-first assignment of removed -> added definitions."""

    def defn(item: tuple[_Unit, int], side: str) -> Defn:
        unit, idx = item
        return (unit.old if side == "old" else unit.new).index.defs[idx]  # type: ignore[union-attr]

    by_kind_new: dict[str, list[tuple[_Unit, int]]] = defaultdict(list)
    for item in news:
        by_kind_new[defn(item, "new").kind].append(item)
    candidates: list[tuple[Any, ...]] = []
    for o in olds:
        od = defn(o, "old")
        if od.kind == "module" or len(od.match_tokens) < opts.min_rename_tokens:
            continue
        group = by_kind_new.get(od.kind, [])
        if not group:
            continue
        if len(group) > budget[0]:
            notes.add("rename_detection_skipped_limit")
            continue
        budget[0] -= len(group)
        for n in group:
            if cross_file and n[0].uid == o[0].uid:
                continue
            nd = defn(n, "new")
            if len(nd.match_tokens) < opts.min_rename_tokens:
                continue
            lo, hi = sorted((len(od.match_tokens), len(nd.match_tokens)))
            if lo / hi < opts.rename_similarity:
                continue
            score = similarity(od, nd)
            if score >= opts.rename_similarity:
                candidates.append(
                    (
                        -score,
                        od.last_name != nd.last_name,
                        _ref_sort(o[0], od),
                        _ref_sort(n[0], nd),
                        o,
                        n,
                        score,
                    )
                )
    candidates.sort(key=lambda c: c[:4])
    used_old: set[tuple[int, int]] = set()
    used_new: set[tuple[int, int]] = set()
    out = []
    for *_, o, n, score in candidates:
        ok, nk = (o[0].uid, o[1]), (n[0].uid, n[1])
        if ok in used_old or nk in used_new:
            continue
        used_old.add(ok)
        used_new.add(nk)
        out.append((o, n, score))
    return out


def _pair_group(
    old_defs: list[Defn], new_defs: list[Defn], olds: list[int], news: list[int]
) -> list[tuple[int, int]]:
    """Pair same-name definitions (overloads, redefinitions) by signature, then body, then order."""

    if len(olds) == 1 and len(news) == 1:
        return [(olds[0], news[0])]
    pairs: list[tuple[int, int]] = []
    rest_old, rest_new = list(olds), list(news)
    passes = (
        lambda d: (d.signature, d.body),
        lambda d: d.signature,
        lambda d: d.body,
    )
    for key_of in passes:
        for oi in list(rest_old):
            for ni in rest_new:
                if key_of(old_defs[oi]) == key_of(new_defs[ni]):
                    pairs.append((oi, ni))
                    rest_old.remove(oi)
                    rest_new.remove(ni)
                    break
    pairs.extend(zip(rest_old, rest_new, strict=False))
    return sorted(pairs)


def _match_in_file(unit: _Unit, opts: ExtractionOptions, notes: set[str]) -> None:
    old_defs = unit.old.index.defs if unit.old else []
    new_defs = unit.new.index.defs if unit.new else []
    old_groups: dict[tuple[str, str], list[int]] = defaultdict(list)
    new_groups: dict[tuple[str, str], list[int]] = defaultdict(list)
    for i, d in enumerate(old_defs):
        old_groups[(d.base_qualname, d.kind)].append(i)
    for i, d in enumerate(new_defs):
        new_groups[(d.base_qualname, d.kind)].append(i)
    matched_old: set[int] = set()
    matched_new: set[int] = set()
    for group in sorted(old_groups.keys() & new_groups.keys()):
        for oi, ni in _pair_group(old_defs, new_defs, old_groups[group], new_groups[group]):
            unit.matched.append((oi, ni, "key", 1.0))
            matched_old.add(oi)
            matched_new.add(ni)
    left_old = [i for i in range(len(old_defs)) if i not in matched_old]
    left_new = [i for i in range(len(new_defs)) if i not in matched_new]
    if left_old and left_new:
        budget = [opts.max_similarity_pairs]
        pairs = _greedy_pairs(
            [(unit, i) for i in left_old], [(unit, i) for i in left_new], opts, budget, notes
        )
        taken_old = set()
        taken_new = set()
        for (_u, oi), (_u2, ni), score in pairs:
            od, nd = old_defs[oi], new_defs[ni]
            origin = "renamed" if od.parent_name == nd.parent_name else "moved"
            unit.matched.append((oi, ni, origin, score))
            taken_old.add(oi)
            taken_new.add(ni)
        left_old = [i for i in left_old if i not in taken_old]
        left_new = [i for i in left_new if i not in taken_new]
    unit.unmatched_old = left_old
    unit.unmatched_new = left_new


