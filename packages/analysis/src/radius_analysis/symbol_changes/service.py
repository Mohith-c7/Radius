@dataclass(frozen=True, slots=True)
class ExtractionOptions:
    """Tunable limits and thresholds. All defaults are deterministic."""

    ignore_globs: tuple[str, ...] = DEFAULT_IGNORE_GLOBS
    detect_generated_headers: bool = True
