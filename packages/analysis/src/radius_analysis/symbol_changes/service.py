"""Symbol-level change extraction service (LK-01).

``extract_symbol_changes(repo_base, repo_head, diff_or_refs, options)`` turns a
unified diff plus the base/head snapshots into a :class:`SymbolChangeSet`.

Pipeline per file: parse the diff -> decide ignore / file-level / symbol-level
-> index base and head definitions -> match definitions by (qualified name,
kind) -> match leftovers by body similarity (rename / move / move between
files) -> attribute every changed line to its innermost symbol or to an
``unattributed`` bucket -> classify each touched symbol. Nothing here raises on
bad input: any per-file failure degrades to a file-level unit with a note.
"""

