def _attribute(unit: _Unit, opts: ExtractionOptions) -> None:
    unattr: dict[tuple[int, str], list[set[int]]] = {}

    def to_unattributed(hunk_index: int, reason: str, is_new: bool, line: int) -> None:
        sets = unattr.setdefault((hunk_index, reason), [set(), set()])
        sets[1 if is_new else 0].add(line)

    for hunk in unit.fd.hunks:
        for dl in hunk.lines:
            if dl.tag == " ":
                continue
            is_new = dl.tag == "+"
            line = dl.new_no if is_new else dl.old_no
            side = unit.new if is_new else unit.old
            if side is None or line is None or not 1 <= line <= side.index.line_count:
                to_unattributed(hunk.index, "out_of_range", is_new, line or 0)
                continue
            text = side.lines[line - 1]
            owner = side.owner[line]
            if owner >= 0:
                if side.index.defs[owner].kind in _CONTAINER_KINDS and not text.strip():
                    to_unattributed(hunk.index, "blank_between_members", is_new, line)
                    continue
                target = owner
            elif line in side.index.import_lines:
                to_unattributed(hunk.index, "import", is_new, line)
                continue
            elif _is_blank_or_comment(text, unit.language):
                to_unattributed(hunk.index, "blank_or_comment", is_new, line)
                continue
            elif side.index.module_index is not None and opts.module_pseudo_symbol:
                target = side.index.module_index
            else:
                to_unattributed(hunk.index, "module_level", is_new, line)
                continue
            side_name = "new" if is_new else "old"
            entry = unit.attr.setdefault((side_name, target), {}).setdefault(
                hunk.index, [set(), set()]
            )
            entry[1 if is_new else 0].add(line)
            unit.changed_text.setdefault((side_name, target), []).append(text)
    headers = {h.index: h for h in unit.fd.hunks}
    for (hunk_index, reason), (old_lines, new_lines) in sorted(unattr.items()):
        h = headers[hunk_index]
        unit.unattributed.append(
            UnattributedHunk(
                language=unit.language,
                reason=reason,
                hunk=SymbolHunk(
                    path=unit.path,
                    hunk_index=hunk_index,
                    old_start=h.old_start,
                    old_count=h.old_count,
                    new_start=h.new_start,
                    new_count=h.new_count,
                    old_lines=compress_lines(old_lines),
                    new_lines=compress_lines(new_lines),
                ),
            )
        )


def _hunks_for(units: list[tuple[_Unit, str, int]]) -> tuple[SymbolHunk, ...]:
    """Merge the old-side and new-side line attributions into per-(path, hunk) entries."""

    merged: dict[tuple[str, int], tuple[set[int], set[int], Any]] = {}
    for unit, side, idx in units:
        headers = {h.index: h for h in unit.fd.hunks}
        path = unit.path if side == "new" else (unit.old_path or unit.path)
        for hunk_index, (old_lines, new_lines) in unit.attr.get((side, idx), {}).items():
            entry = merged.setdefault((path, hunk_index), (set(), set(), headers[hunk_index]))
            entry[0].update(old_lines)
            entry[1].update(new_lines)
    out = [
        SymbolHunk(
            path=path,
            hunk_index=hunk_index,
            old_start=h.old_start,
            old_count=h.old_count,
            new_start=h.new_start,
            new_count=h.new_count,
            old_lines=compress_lines(old_lines),
            new_lines=compress_lines(new_lines),
        )
        for (path, hunk_index), (old_lines, new_lines, h) in merged.items()
    ]
    return tuple(sorted(out, key=lambda x: (x.path, x.hunk_index)))


# --------------------------------------------------------------------------- classification


def _structural_kinds(o: Defn, n: Defn) -> list[ChangeKind]:
    kinds: list[ChangeKind] = []
    if o.signature != n.signature:
        kinds.append(ChangeKind.MODIFIED_SIGNATURE)
    if o.body != n.body:
        kinds.append(ChangeKind.MODIFIED_BODY)
    if o.decorators != n.decorators:
        kinds.append(ChangeKind.DECORATOR_OR_ANNOTATION_CHANGED)
    return kinds


def _suppression_note(texts: list[str]) -> bool:
    return any(_SUPPRESSION_RE.search(t) for t in texts)


def _emit_pair(
    uo: _Unit,
    oi: int,
    un: _Unit,
    ni: int,
    origin: str,
    score: float,
) -> ChangedSymbol | None:
    assert uo.old is not None and un.new is not None
    o = uo.old.index.defs[oi]
    n = un.new.index.defs[ni]
    hunks = _hunks_for([(uo, "old", oi), (un, "new", ni)])
    notes: list[str] = []
    structural = _structural_kinds(o, n)
    if origin == "key" and not hunks and not un.file_renamed:
        return None
    confidence = 1.0
    secondary: list[ChangeKind] = []
    if origin in {"renamed", "moved"}:
        primary = ChangeKind.RENAMED if origin == "renamed" else ChangeKind.MOVED
        secondary = structural
        confidence = round(score, 3)
        if origin == "moved" and o.last_name != n.last_name:
            notes.append("renamed_and_moved")
        if o.body != n.body:
            notes.append(f"{origin}_with_body_changes")
    elif origin == "cross":
        primary = ChangeKind.MOVED_BETWEEN_FILES
        secondary = structural
        confidence = round(score, 3)
        if o.last_name != n.last_name:
            notes.append("renamed_and_moved")
        if o.body != n.body:
            notes.append("moved_with_body_changes")
    elif un.file_renamed:
        primary = ChangeKind.MOVED_BETWEEN_FILES
        secondary = structural
    elif structural:
        primary, secondary = structural[0], structural[1:]
    elif o.docstring != n.docstring or uo.old.comments_of(oi) != un.new.comments_of(ni):
        primary = ChangeKind.DOCSTRING_OR_COMMENT_ONLY
    else:
        primary = ChangeKind.FORMATTING_ONLY
    if un.file_renamed and origin != "cross":
        notes.append("file_renamed")
    texts = uo.changed_text.get(("old", oi), []) + un.changed_text.get(("new", ni), [])
    if _suppression_note(texts):
        notes.append("suppression_marker_changed")
    return ChangedSymbol(
        symbol_id=symbol_id(un.language, un.path, n),
        key=symbol_key(un.language, un.path, n),
        language=un.language,
        path=un.path,
        qualified_name=n.qualname,
        kind=n.kind,
        change_kind=primary,
        old_symbol_id=symbol_id(uo.language, uo.old_path or uo.path, o),
        new_symbol_id=symbol_id(un.language, un.path, n),
        old_path=uo.old_path or uo.path if (uo.old_path or uo.path) != un.path else None,
        old_qualified_name=o.qualname if o.qualname != n.qualname else None,
        old_range=LineRange(o.start, o.end),
        new_range=LineRange(n.start, n.end),
        old_signature=o.display,
        new_signature=n.display,
        old_body_hash=o.body_hash,
        new_body_hash=n.body_hash,
        secondary_kinds=tuple(dict.fromkeys(secondary)),
        hunks=hunks,
        confidence=confidence,
        notes=tuple(dict.fromkeys(notes)),
    )


def _emit_one_sided(unit: _Unit, side: str, idx: int) -> ChangedSymbol:
    assert (unit.new if side == "new" else unit.old) is not None
    s = unit.new if side == "new" else unit.old
    d = s.index.defs[idx]  # type: ignore[union-attr]
    path = unit.path if side == "new" else (unit.old_path or unit.path)
    sid = symbol_id(unit.language, path, d)
    added = side == "new"
    notes: list[str] = []
    if _suppression_note(unit.changed_text.get((side, idx), [])):
        notes.append("suppression_marker_changed")
    return ChangedSymbol(
        symbol_id=sid,
        key=symbol_key(unit.language, path, d),
        language=unit.language,
        path=path,
        qualified_name=d.qualname,
        kind=d.kind,
        change_kind=ChangeKind.ADDED if added else ChangeKind.REMOVED,
        old_symbol_id=None if added else sid,
        new_symbol_id=sid if added else None,
        old_range=None if added else LineRange(d.start, d.end),
        new_range=LineRange(d.start, d.end) if added else None,
        old_signature=None if added else d.display,
        new_signature=d.display if added else None,
        old_body_hash=None if added else d.body_hash,
        new_body_hash=d.body_hash if added else None,
        hunks=_hunks_for([(unit, side, idx)]),
        confidence=1.0,
        notes=tuple(notes),
    )


def _file_level_symbol(
    fd: FileDiff, language: str, path: str, old_path: str | None, notes: list[str]
) -> ChangedSymbol:
    if fd.status is FileStatus.ADDED or fd.status is FileStatus.COPIED:
        kind = ChangeKind.ADDED
    elif fd.status is FileStatus.DELETED:
        kind = ChangeKind.REMOVED
    elif fd.status is FileStatus.RENAMED and not fd.hunks:
        kind = ChangeKind.MOVED_BETWEEN_FILES
    else:
        kind = ChangeKind.MODIFIED_BODY
    secondary = (ChangeKind.MOVED_BETWEEN_FILES,) if kind is ChangeKind.MODIFIED_BODY and (
        fd.status is FileStatus.RENAMED
    ) else ()
    hunks: list[SymbolHunk] = []
    for h in fd.hunks:
        hunks.append(
            SymbolHunk(
                path=path,
                hunk_index=h.index,
                old_start=h.old_start,
                old_count=h.old_count,
                new_start=h.new_start,
                new_count=h.new_count,
                old_lines=compress_lines(h.deleted),
                new_lines=compress_lines(h.added),
            )
        )
    sig = short_hash("")
    base = f"{language}:{path}::{FILE_SYMBOL}#file"
    old_base = f"{language}:{old_path or path}::{FILE_SYMBOL}#file"
    new_range = None
    if fd.status in {FileStatus.ADDED, FileStatus.COPIED} and fd.hunks:
        new_range = LineRange(1, max(1, sum(h.new_count for h in fd.hunks)))
    return ChangedSymbol(
        symbol_id=f"{base}@{sig}",
        key=base,
        language=language,
        path=path,
        qualified_name=FILE_SYMBOL,
        kind="file",
        change_kind=kind,
        old_symbol_id=None if kind is ChangeKind.ADDED else f"{old_base}@{sig}",
        new_symbol_id=None if kind is ChangeKind.REMOVED else f"{base}@{sig}",
        old_path=old_path if old_path and old_path != path else None,
        new_range=new_range,
        secondary_kinds=secondary,
        hunks=tuple(hunks),
        confidence=_DEGRADED_CONFIDENCE,
        notes=tuple(dict.fromkeys(notes)),
    )


