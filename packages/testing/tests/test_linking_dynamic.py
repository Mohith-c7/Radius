def _handmade(tmp_path, *, contexts, rows, arcs=None):
    db = tmp_path / "h.db"
    conn = sqlite3.connect(db)
    conn.execute("create table file (id integer primary key, path text)")
    conn.execute("create table context (id integer primary key, context text)")
    conn.execute("create table line_bits (file_id integer, context_id integer, numbits blob)")
    conn.execute("create table arc (file_id integer, context_id integer, fromno integer, tono integer)")
    conn.execute("insert into file values (1, '/workspace/src/a.py')")
    conn.executemany("insert into context values (?, ?)", contexts)
    conn.executemany("insert into line_bits values (?, ?, ?)", rows)
    conn.executemany("insert into arc values (?, ?, ?, ?)", arcs or [])
    conn.commit()
    conn.close()
    return db.read_bytes()


