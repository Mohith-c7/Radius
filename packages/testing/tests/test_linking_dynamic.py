def make_project(root: Path) -> Path:
    repo = root / "repo"
    (repo / "src").mkdir(parents=True)
    (repo / "tests").mkdir()
    (repo / "src" / "calc.py").write_text(CALC)
    (repo / "tests" / "test_calc.py").write_text(TESTS)
    return repo


def host_coverage(repo: Path, files=("tests/test_calc.py",)) -> tuple[bytes, bytes]:
    """Run the driver on the host against trusted fixture code; return (.coverage, junit)."""

    out = repo.parent / "out"
    out.mkdir(exist_ok=True)
    env = {k: v for k, v in os.environ.items() if not k.startswith(("COV_CORE", "COVERAGE"))}
    proc = subprocess.run(  # noqa: S603 - fixed argv, trusted test fixture
        [sys.executable, "-c", DRIVER_SCRIPT, str(out / ".coverage"), str(out / "junit.xml"), *files],
        cwd=repo, env=env, capture_output=True, text=True, timeout=120, check=False,
    )  # fmt: skip
    assert (out / ".coverage").is_file(), proc.stdout + proc.stderr
    return (out / ".coverage").read_bytes(), (out / "junit.xml").read_bytes()


