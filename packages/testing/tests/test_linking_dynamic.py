def test_run_collecting_ignores_symlink_and_oversize_artifacts(tmp_path):
    repo = make_project(tmp_path)
    secret = tmp_path / "secret.txt"
    secret.write_text("TOP SECRET")

    class _Evil(_ArtifactLauncher):
        def __call__(self, argv, **kwargs):
            mounts = {
                v.split("target=")[1].split(",")[0]: Path(v.split("source=")[1].split(",")[0])
                for f, v in zip(argv, argv[1:], strict=False)
                if f == "--mount"
            }
            try:
                (mounts["/results"] / ".coverage").symlink_to(secret)
            except OSError:
                pytest.skip("symlinks unavailable")
            (mounts["/results"] / "junit.xml").write_bytes(b"x" * 100)
            return _Done()

    class _Done:
        def wait(self, timeout=None):
            return 0

        def kill(self):
            pass

    runner = _runner(_Evil(repo))
    plan = DynamicCoverageLinker(runner, enabled=True).plan_for(["tests/test_calc.py"])
    result, artifacts = runner.run_collecting(plan, repo, (".coverage", "junit.xml"), max_artifact_bytes=10)
    assert isinstance(result, RunResult) and result.status in set(RunStatus)
    assert artifacts == {}  # symlink and oversize file both dropped


# ----------------------------------------------------- Docker integration ---
COV_IMAGE = os.environ.get("RADIUS_SANDBOX_COV_IMAGE", "radius-sandbox-cov:latest")


def _docker_cov_ready() -> bool:
    docker = shutil.which("docker")
    if docker is None:
        return False
    try:
        probe = subprocess.run(
            [docker, "run", "--rm", "--pull", "never", "--network", "none", COV_IMAGE, "python", "-c", "import coverage, pytest"],
            capture_output=True, timeout=60, check=False,
        )  # fmt: skip
    except (OSError, subprocess.SubprocessError):
        return False
    return probe.returncode == 0


requires_cov_docker = pytest.mark.skipif(
    not _docker_cov_ready(),
    reason=(
        f"docker or image {COV_IMAGE!r} with pytest+coverage unavailable "
        "(build: FROM radius-sandbox-test + pip install coverage; set RADIUS_SANDBOX_COV_IMAGE)"
    ),
)


@requires_cov_docker
def test_docker_integration_dynamic_links_in_real_sandbox(tmp_path):
    repo = make_project(tmp_path)
    runner = ContainerSandboxRunner(SandboxConfig(image=COV_IMAGE, timeout_seconds=120))
    result = DynamicCoverageLinker(runner, enabled=True).link(repo, ["tests/test_calc.py"], TARGETS)
    assert result.status == "ok", result.notes
    got = {(lk.symbol_id.rsplit("::", 1)[-1], lk.test_id.split("::", 1)[1]) for lk in result.links.links}
    assert {("add", "test_add"), ("add", "test_helper"), ("hidden", "test_dynamic"), ("sub", "test_fixture")} <= got
    assert ("add", "TestK::test_nothing") not in got
    host = {lk.key for lk in links_from_coverage(read_coverage_bytes(host_coverage(repo)[0]), TARGETS)[0]}
    assert host == set(result.links.by_key())  # sandbox and host runs agree
