class _ArtifactLauncher:
    """Fake container launcher: 'runs' the driver on the host and writes /results."""

    def __init__(self, repo: Path, *, write_coverage=True, returncode=0, payload: bytes | None = None):
        self.repo, self.write_coverage, self.returncode, self.payload = repo, write_coverage, returncode, payload
        self.argvs: list[list[str]] = []

    def __call__(self, argv, **kwargs):
        self.argvs.append(argv)
        mounts = {
            v.split("target=")[1].split(",")[0]: Path(v.split("source=")[1].split(",")[0])
            for f, v in zip(argv, argv[1:], strict=False)
            if f == "--mount"
        }
        if self.write_coverage:
            data, junit = self.payload, None
            if data is None:
                data, junit = host_coverage(self.repo)
            (mounts["/results"] / ".coverage").write_bytes(data)
            if junit:
                (mounts["/results"] / "junit.xml").write_bytes(junit)
        returncode = self.returncode

        class _P:
            def wait(self, timeout=None):
                return returncode

            def kill(self):  # pragma: no cover
                pass

        return _P()


def _runner(launcher) -> ContainerSandboxRunner:
    done = subprocess.CompletedProcess([], 0)
    return ContainerSandboxRunner(
        SandboxConfig(),
        launcher=launcher,
        aux_runner=lambda *a, **k: done,
        which=lambda name: "/usr/bin/docker",
        probe=lambda *a, **k: done,
    )


def test_end_to_end_through_runner_collects_artifact_and_links(tmp_path):
    repo = make_project(tmp_path)
    launcher = _ArtifactLauncher(repo)
    result = DynamicCoverageLinker(_runner(launcher), enabled=True).link(repo, ["tests/test_calc.py"], TARGETS)
    assert result.status == "ok"
    argv = launcher.argvs[0]
    assert "--network" in argv and argv[argv.index("--network") + 1] == "none"
    assert result.links.by_key()[(ADD.symbol_id, "tests/test_calc.py::test_add")].score >= 0.7
    assert "tests/test_calc.py::test_add" in result.executed_tests
    assert result.contexts >= 5
    assert result.links.algo_version == "dynamic-cov-link-v1"


