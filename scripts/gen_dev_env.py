"""Create ``.env`` for LOCAL DEVELOPMENT from ``.env.example`` with random secrets.

Used by ``make env`` and ``scripts/dev.ps1 env``. It never overwrites an existing
file. Every secret is generated on this machine, so no shared literal key exists
that could be valid anywhere else:

* ``SESSION_SECRET``: random, replaces the public placeholder.
* ``RADIUS_API_KEY``: random dev key. ``docker-compose.dev.yml`` registers it as
  the legacy ``API_KEYS`` entry for the dev organization, and the dashboard proxy
  sends it server-side. Dev only; do not reuse it anywhere.
* ``GITHUB_DEFAULT_ORGANIZATION_ID`` / ``NEXT_PUBLIC_RADIUS_ORGANIZATION_ID``: the
  organization id used by ``scripts/seed_demo.py`` so the demo data is visible.

Usage: ``python scripts/gen_dev_env.py [--env-file .env] [--example .env.example]``
"""

from __future__ import annotations

import argparse
import re
import secrets
import sys
from pathlib import Path

DEMO_ORG_ID = "00000000-0000-4000-8000-000000000001"
ROOT = Path(__file__).resolve().parent.parent


def render(example_text: str) -> str:
    """Return a dev ``.env`` body: the example with generated values filled in."""

    values = {
        "SESSION_SECRET": secrets.token_urlsafe(48),
        "RADIUS_API_KEY": "dev_" + secrets.token_urlsafe(32),
        "GITHUB_DEFAULT_ORGANIZATION_ID": DEMO_ORG_ID,
        "NEXT_PUBLIC_RADIUS_ORGANIZATION_ID": DEMO_ORG_ID,
        "EMAIL_DELIVERY_MODE": "log",
        "DEV_AUTO_VERIFY_EMAIL": "true",
    }
    lines = example_text.splitlines()
    seen: set[str] = set()
    out: list[str] = []
    for line in lines:
        match = re.match(r"^([A-Z][A-Z0-9_]*)=", line)
        if match and match.group(1) in values:
            name = match.group(1)
            out.append(f"{name}={values[name]}")
            seen.add(name)
        else:
            out.append(line)
    missing = [name for name in values if name not in seen]
    if missing:
        out.append("")
        out.append("# Added by scripts/gen_dev_env.py (local development only)")
        out.extend(f"{name}={values[name]}" for name in missing)
    header = (
        "# LOCAL DEVELOPMENT .env generated by scripts/gen_dev_env.py.\n"
        "# Secrets below are random and machine-local. Do not commit or reuse them.\n"
        "# For a production-like deployment start from .env.example instead (docs/operations/INSTALL.md).\n"
    )
    return header + "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--env-file", default=str(ROOT / ".env"))
    parser.add_argument("--example", default=str(ROOT / ".env.example"))
    args = parser.parse_args(argv)
    target = Path(args.env_file)
    if target.exists():
        print(f"{target} exists; leaving it unchanged.")
        return 0
    text = render(Path(args.example).read_text(encoding="utf-8"))
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"created {target} with random local-dev secrets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
